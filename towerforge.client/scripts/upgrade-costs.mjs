const out = (file) => new URL(`../src/constants/${file}`, import.meta.url);

// Costs under ten million exactly; above, 4 significant figures (as the game shows them).
function num(v) {
    if (Math.abs(v) < 1e7) return String(Math.round(v));
    const [m, e] = v.toExponential(3).split('e');
    return `${m.replace(/\.?0+$/, '')}e${Number(e)}`;
}

// A name as a TS key: single quotes unless it has one ("Fast's Ultimate").
const key = (name) => (name.includes("'") ? JSON.stringify(name) : `'${name}'`);

function wrap(items, indent, first = indent, width = 104) {
    const lines = [];
    let cur = first;
    for (const it of items) {
        if (cur.length + it.length + 2 > width && cur.trim() !== '' && cur.trim() !== '[') {
            lines.push(cur.trimEnd());
            cur = indent;
        }
        cur += `${it}, `;
    }
    if (cur.trim()) lines.push(cur.trimEnd());
    return lines.join('\n');
}

// ── Workshop ────────────────────────────────────────────────
// Our stat names → the SDK's.
const WS_NAMES = {
    'Damage/Meter': 'Damage / Meter', 'Super Critical Chance': 'Super Crit Chance',
    'Super Critical Mult': 'Super Crit Mult', 'Defense %': 'Defense Percent', 'Thorn Damage': 'Thorns',
    'Cash/Wave': 'Cash / Wave', 'Coin/Kill Bonus': 'Coins / Kill Bonus', 'Coin/Wave': 'Coins / Wave',
    'Free Atk Upgrade': 'Free Attack Upgrade', 'Free Def Upgrade': 'Free Defense Upgrade',
    'Free Util Upgrade': 'Free Utility Upgrade', 'Interest/Wave': 'Interest / Wave', 'Max Amount': 'Max Recovery',
    'Enemy Atk Level Skip': 'Enemy Attack Level Skip', 'Enemy HP Level Skip': 'Enemy Health Level Skip',
};
const LONG = 300;
const wsRows = Object.values(WS_STATS).flat().map(([name, max]) => {
    const table = workshop[WS_NAMES[name] ?? name];
    if (!table || Object.keys(table).length - 1 !== max) throw new Error(`Workshop ${name}: no table of ${max} levels`);
    const per = Array.from({ length: max }, (_, l) => table[String(l)].coins);   // entry l buys level l + 1
    const step = max > LONG ? 10 : 1;
    const vals = [];
    for (let k = 0; k < max; k += step) vals.push(per.slice(k, k + step).reduce((a, b) => a + b, 0));
    return `    ${key(name)}: [${step}, [\n${wrap(vals.map(num), '        ')}\n    ]],`;
});
writeFileSync(out('workshopCosts.ts'), `// ============================================================
//  TowerForge Companion — Workshop coin costs
//  Coins for every workshop level, before the Workshop Discount labs —
//  the game's own upgrade table, as TheTowerSDK ships it (MIT, npm
//  \`thetowersdk\`, data/workshop/table.json). 46 of the 48 stats match the
//  wiki's cost tables level for level; the other two (Rend Armor Mult,
//  Wall Health) are in docs/optimizer.md.
//  Generated by scripts/upgrade-costs.mjs — regenerate rather than edit.
// ============================================================

// [levels per entry, coins for each entry]. Stats up to ${LONG} levels list
// every level; longer ones the total of each 10 levels (the last entry
// covers whatever is left). Entry 0 buys level 1.
export const WS_COIN_COSTS: Record<string, [number, number[]]> = {
${wsRows.join('\n')}
};
`);

