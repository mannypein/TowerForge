// "27:46:00" or "10d 19h 11m" → hours.
function hours(d) {
    if (d.includes(':')) {
        const [h, m, s] = d.split(':').map(Number);
        return h + m / 60 + s / 3600;
    }
    const part = (unit) => Number(d.match(new RegExp(`(\\d+)${unit}`))?.[1] ?? 0);
    return part('d') * 24 + part('h') + part('m') / 60;
}

const labRows = LABS.flatMap(g => g.l).map(([name, max]) => {
    const lab = catalog.get((LAB_NAMES[name] ?? name).toLowerCase())
        ?? catalog.get(name.replace(/ Lab$/, '').toLowerCase());
    if (!lab) throw new Error(`Lab ${name}: not in the catalog`);
    const levels = lab.levels.filter(x => x.level >= 1).sort((a, b) => a.level - b.level).slice(0, max);
    levels.forEach((x, i) => { if (x.level !== i + 1) throw new Error(`Lab ${name}: level ${i + 1} missing`); });
    const mins = levels.map(x => String(Math.round(hours(x.duration) * 60)));
    const coins = levels.map(x => num(x.cost));
    const list = (items) => wrap(items, '         ', '        [').replace(/,$/, '');
    return `    ${key(name)}: [\n${list(mins)}],\n${list(coins)}],\n    ],`;
});
